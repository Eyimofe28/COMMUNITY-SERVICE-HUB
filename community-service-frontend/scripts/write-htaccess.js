// Runs automatically after `npm run build` (the "postbuild" script).
//
// When the app is built for a sub-folder such as https://mcisstudents.mvsu.edu/~username/
// (PUBLIC_URL=/~username), Apache needs an .htaccess file so that reloading or opening a
// direct link like /~username/student/dashboard serves index.html instead of a 404.
// Locally (no PUBLIC_URL) nothing is written.

const fs = require("fs");
const path = require("path");

// Same files react-scripts reads, so PUBLIC_URL can live in .env.production.local
for (const file of [".env.production.local", ".env.local", ".env.production", ".env"]) {
  require("dotenv").config({ path: path.join(__dirname, "..", file), quiet: true });
}

const publicUrl = (process.env.PUBLIC_URL || "").replace(/\/+$/, "");
const target = path.join(__dirname, "..", "build", ".htaccess");

if (!publicUrl) {
  console.log("PUBLIC_URL not set - skipping .htaccess (only needed on the school server).");
  process.exit(0);
}

const htaccess = `# Generated by scripts/write-htaccess.js - serve index.html for app routes
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase ${publicUrl}/
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule . ${publicUrl}/index.html [L]
</IfModule>
`;

fs.writeFileSync(target, htaccess);
console.log(`Wrote build/.htaccess for ${publicUrl}/`);
