// =============================================================================
// Signup (registration) page
// -----------------------------------------------------------------------------
// Flow: user fills the form -> every field is validated live -> POST /api/auth/signup
// -> on success they are sent to the login page with an "Account created" notice.
//
// INPUT VALIDATION: each field is checked with the shared rules in
//   utils/validation.js and utils/passwordRules.js (copies of the backend rules).
//   Errors show under a field once it has been left, or for every field when
//   Continue is pressed. Nothing is sent until the whole form is valid, and the
//   backend validates everything again.
// SECURITY: Confirm Password prevents typos locking users out; the password is
//   only sent once and never stored in the browser. Admin accounts cannot be
//   created here - the role is limited to student/faculty (also on the backend).
// ERROR HANDLING: server answers such as "Email already registered", rate limits
//   or an unreachable server are shown in the card.
// REUSABILITY: the field wiring (value, change, blur, error text) is generated by
//   fieldProps() instead of being repeated for every input.
// =============================================================================

import { Box, Button, TextField, Typography, Paper, IconButton, Alert } from "@mui/material";
import ArrowBackIosNewIcon from "@mui/icons-material/ArrowBackIosNew";
import { useState } from "react";
import { useNavigate } from "react-router-dom";
import api, { getErrorMessage } from "../../api/axios";
import PasswordRequirements from "../../components/PasswordRequirements";
import { isPasswordValid } from "../../utils/passwordRules";
import { validateName, validateEmail, validateDepartment } from "../../utils/validation";
import { setLoginNotice } from "../../utils/auth";

export default function Signup() {
  const navigate = useNavigate();

  const [form, setForm] = useState({
    firstName: "",
    lastName: "",
    email: "",
    password: "",
    confirmPassword: "",
    role: "student",
    department: ""
  });

  // Fields the user has left (errors only show after that, or after pressing Continue)
  const [touched, setTouched] = useState({});
  const [submitted, setSubmitted] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [serverError, setServerError] = useState("");

  // Current error message for every field ("" = valid), recalculated on each change
  const errors = {
    firstName: validateName(form.firstName, "First name"),
    lastName: validateName(form.lastName, "Last name"),
    email: validateEmail(form.email),
    password: isPasswordValid(form.password) ? "" : "Password does not meet all the requirements below.",
    confirmPassword:
      form.confirmPassword === form.password && form.confirmPassword ? "" : "Passwords do not match.",
    department: form.role === "faculty" ? validateDepartment(form.department) : "",
  };
  const hasErrors = Object.values(errors).some(Boolean);

  // Props shared by every text field: value, change/blur handlers, error display
  const showError = (field) => (touched[field] || submitted) && !!errors[field];
  const fieldProps = (field) => ({
    name: field,
    value: form[field],
    onChange: handleChange,
    onBlur: () => setTouched((prev) => ({ ...prev, [field]: true })),
    error: showError(field),
    helperText: showError(field) ? errors[field] : " ",
  });

  function handleChange(e) {
    setForm({ ...form, [e.target.name]: e.target.value });
  }

  const handleSignup = async (e) => {
    e.preventDefault(); // stay on the page; the form is handled here
    setSubmitted(true);
    setServerError("");
    if (hasErrors) return; // show every field's error instead of sending

    setSubmitting(true);
    try {
      // Only the fields the backend needs (Confirm Password stays in the browser)
      await api.post("/auth/signup", {
        firstName: form.firstName,
        lastName: form.lastName,
        email: form.email.trim().toLowerCase(),
        password: form.password,
        role: form.role,
        department: form.role === "faculty" ? form.department : undefined,
      });
      setLoginNotice("Account created! You can now log in.");
      navigate("/login");
    } catch (error) {
      setServerError(getErrorMessage(error, "Sign up failed. Please try again."));
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <Box
      sx={{
        minHeight: "100vh",
        py: 4,
        boxSizing: "border-box",
        background: "#0B3D2E",
        display: "flex",
        justifyContent: "center",
        alignItems: "center",
        position: "relative",
      }}
    >
      {/* FLOATING GLOW EFFECT */}
      <Box
        sx={{
          position: "absolute",
          width: 480,
          height: 680,
          filter: "blur(60px)",
          background: "rgba(0, 255, 120, 0.18)",
          borderRadius: "40px",
          animation: "pulse 4s infinite ease-in-out",
          "@keyframes pulse": {
            "0%": { opacity: 0.5 },
            "50%": { opacity: 0.9 },
            "100%": { opacity: 0.5 }
          }
        }}
      />

      {/* MAIN CARD */}
      <Paper
        component="form"
        noValidate
        onSubmit={handleSignup}
        elevation={8}
        sx={{
          padding: 5,
          width: 570,
          borderRadius: "30px",
          textAlign: "center",
          backdropFilter: "blur(6px)",
          position: "relative",
          // ✨ GLOW AROUND CARD
          boxShadow: "0 0 25px 5px rgba(0, 255, 140, 1)",
        }}
        
      >
        
        {/* BACK BUTTON */}
        <IconButton
          onClick={() => navigate("/welcome")}
          sx={{
            position: "absolute",
            top: 20,
            left: 20,
            color: "#0B3D2E",
          }}
        >
          <ArrowBackIosNewIcon />
        </IconButton>

        {/* TITLE */}
        <Typography variant="h4" sx={{ mb: 3, fontWeight: "bold", mt: 1 }}>
          Create Account
        </Typography>

        {serverError && (
          <Alert severity="error" sx={{ mb: 2, textAlign: "left" }}>
            {serverError}
          </Alert>
        )}

        {/* INPUTS */}
        <Box sx={{ display: "flex", gap: 2 }}>
          <TextField label="First Name" fullWidth sx={{ mb: 0.5 }} {...fieldProps("firstName")} />
          <TextField label="Last Name" fullWidth sx={{ mb: 0.5 }} {...fieldProps("lastName")} />
        </Box>

        <TextField
          label="MVSU Email"
          placeholder="first.last@mvsu.edu"
          fullWidth
          sx={{ mb: 0.5 }}
          {...fieldProps("email")}
        />

        <TextField label="Password" type="password" autoComplete="new-password" fullWidth sx={{ mb: 0.5 }} {...fieldProps("password")} />

        <Box sx={{ mb: 2, px: 0.5 }}>
          <PasswordRequirements password={form.password} />
        </Box>

        <TextField
          label="Confirm Password"
          type="password"
          autoComplete="new-password"
          fullWidth
          sx={{ mb: 0.5 }}
          {...fieldProps("confirmPassword")}
        />

        <TextField
          label="Role"
          select
          name="role"
          value={form.role}
          fullWidth
          SelectProps={{ native: true }}
          sx={{ mb: 2.5 }}
          onChange={handleChange}
        >
          <option value="student">Student</option>
          <option value="faculty">Faculty</option>
        </TextField>

        {form.role === "faculty" && (
          <TextField label="Department" fullWidth sx={{ mb: 0.5 }} {...fieldProps("department")} />
        )}

        {/* SUBMIT BUTTON */}
        <Button
          type="submit"
          variant="contained"
          fullWidth
          disabled={submitting}
          sx={{ py: 1.4, fontSize: "1rem" }}
        >
          {submitting ? "Creating account..." : "Continue"}
        </Button>
      </Paper>
    </Box>
  );
}
