-- Community Service Hub - PostgreSQL schema (Supabase)
--
-- Apply with:  npm run db:schema   (from the project root)
-- WARNING: this drops and recreates every table, deleting all data.
--
-- Naming: table names are lowercase; column names keep their original
-- Mixed_Case and must be double-quoted in queries (e.g. "User_ID"), so the
-- API keeps returning the same field names the frontend expects.

DROP TABLE IF EXISTS communication, attendance, registration, opportunity, student, faculty, users CASCADE;

-- ---------- USERS (base table for every account) ----------
CREATE TABLE users (
    "User_ID"       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "First_Name"    varchar(50)  NOT NULL,
    "Last_Name"     varchar(50)  NOT NULL,
    "Email"         varchar(100) NOT NULL UNIQUE,
    "Password_Hash" varchar(255) NOT NULL,
    "Role"          varchar(10)  NOT NULL CHECK ("Role" IN ('student', 'faculty', 'admin')),
    -- Emails are stored lowercase so lookups are case-insensitive
    CONSTRAINT users_email_lowercase CHECK ("Email" = lower("Email"))
);

-- ---------- STUDENT (one row per student user) ----------
CREATE TABLE student (
    "User_ID"             integer PRIMARY KEY REFERENCES users ("User_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Service_Hours_Total" numeric(5,2) NOT NULL DEFAULT 0
);

-- ---------- FACULTY (one row per faculty user; Approver = can approve opportunities) ----------
CREATE TABLE faculty (
    "User_ID"      integer PRIMARY KEY REFERENCES users ("User_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Faculty_Dept" varchar(100),
    "Approver"     boolean NOT NULL DEFAULT false
);

-- ---------- OPPORTUNITY ----------
CREATE TABLE opportunity (
    "Opportunity_ID"   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Faculty_ID"       integer NOT NULL REFERENCES faculty ("User_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Title"            varchar(255) NOT NULL,
    "Description"      text,
    "Date"             date NOT NULL,
    "Start_Time"       time NOT NULL,
    "End_Time"         time NOT NULL,
    "Duration"         numeric(4,2) NOT NULL,
    "Location"         varchar(255),
    "Person_In_Charge" varchar(100),
    "Approval_Status"  varchar(10) NOT NULL DEFAULT 'Pending'
                       CHECK ("Approval_Status" IN ('Pending', 'Approved', 'Rejected')),
    "Rejection_Reason" text,
    "Approver_ID"      integer REFERENCES faculty ("User_ID") ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX opportunity_faculty_idx  ON opportunity ("Faculty_ID");
CREATE INDEX opportunity_approver_idx ON opportunity ("Approver_ID");

-- ---------- REGISTRATION (student signed up for an opportunity) ----------
CREATE TABLE registration (
    "Registration_ID"     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Student_ID"          integer NOT NULL REFERENCES student ("User_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Opportunity_ID"      integer NOT NULL REFERENCES opportunity ("Opportunity_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Registration_Date"   timestamptz NOT NULL DEFAULT now(),
    "Registration_Status" varchar(12) NOT NULL DEFAULT 'Registered'
                          CHECK ("Registration_Status" IN ('Registered', 'Unregistered')),
    CONSTRAINT uq_student_opportunity UNIQUE ("Student_ID", "Opportunity_ID")
);
CREATE INDEX registration_opportunity_idx ON registration ("Opportunity_ID");

-- ---------- ATTENDANCE (submitted by faculty after the opportunity) ----------
CREATE TABLE attendance (
    "Attendance_ID"  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Student_ID"     integer NOT NULL REFERENCES student ("User_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Opportunity_ID" integer NOT NULL REFERENCES opportunity ("Opportunity_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Attended"       boolean NOT NULL DEFAULT false,
    "Hours_Earned"   numeric(4,2) NOT NULL DEFAULT 0,
    CONSTRAINT uq_attendance UNIQUE ("Student_ID", "Opportunity_ID")
);
CREATE INDEX attendance_opportunity_idx ON attendance ("Opportunity_ID");

-- ---------- COMMUNICATION (faculty announcements per opportunity) ----------
CREATE TABLE communication (
    "Communication_ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Opportunity_ID"   integer NOT NULL REFERENCES opportunity ("Opportunity_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Faculty_ID"       integer NOT NULL REFERENCES faculty ("User_ID") ON DELETE CASCADE ON UPDATE CASCADE,
    "Message_Content"  text NOT NULL,
    "Timestamp"        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX communication_opportunity_idx ON communication ("Opportunity_ID");

-- ---------- SECURITY ----------
-- Only the backend (connecting as the table owner) may read or write data.
-- Row Level Security with NO policies blocks every other role, and the
-- Supabase Data API roles get no privileges at all.
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['users', 'student', 'faculty', 'opportunity', 'registration', 'attendance', 'communication']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('REVOKE ALL ON TABLE %I FROM anon, authenticated', t);
    END LOOP;
END $$;
